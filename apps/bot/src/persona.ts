/** Сериализует базу знаний в компактный текст для системного промпта. */
function renderKnowledge(kb: typeof KNOWLEDGE_BASE): string {
  const list = (items: readonly string[]) => items.map((i) => `  • ${i}`).join("\n");
  const obj = (o: Record<string, string>) =>
    Object.entries(o)
      .map(([k, v]) => `  • «${k}»: ${v}`)
      .join("\n");

  return [
    `КОМПАНИЯ: ${kb.company.name} (${kb.company.brand}), ${kb.company.cities.join(" / ")}.`,
    `Сайт: ${kb.company.site} · Телефон: ${kb.company.phone} · Время: ${kb.company.workingHours}.`,
    ``,
    `ЧЕМ ЗАНИМАЕМСЯ: ${kb.whatWeDo}`,
    `Аукционы: ${kb.auctions.join(", ")}.`,
    ``,
    `ЦЕНА «ПОД КЛЮЧ» ВКЛЮЧАЕТ:\n${list(kb.turnkeyIncludes)}`,
    ``,
    `ЭТАПЫ СДЕЛКИ:\n${list(kb.process)}`,
    `Сроки: ${kb.timeline}`,
    `Логистика: ${kb.logistics}`,
    ``,
    `КАК СЧИТАЕМ ЦЕНУ: ${kb.pricingLogic}`,
    `Что спросить для расчёта:\n${list(kb.calculatorInputs)}`,
    `Возраст/пошлина: ${kb.ageRules}`,
    ``,
    `Гарантии: ${kb.guarantees}`,
    `Оплата: ${kb.payment}`,
    ``,
    `ВОЗРАЖЕНИЯ:\n${obj(kb.objections)}`,
    ``,
    `ССЫЛКИ: расчёт ${kb.links.calculator} · каталог ${kb.links.catalog} · контакты ${kb.links.contacts}`,
  ].join("\n");
}

